/**
 * Shared paper-craft drawing primitives for PEELBEAST sprite authoring.
 *
 * Every sprite in `assets/source/sprites/` is generated from `sprite-sources.mjs`
 * using these helpers, then written out as a STANDALONE `.svg` file. Standalone
 * means an artist can open any single sprite in Inkscape/Illustrator, redraw it,
 * and the raster pipeline (`build-sprites.mjs`) will pick the change up without
 * touching the generator.
 *
 * The visual language is taken from the v0.8 reference sheet
 * (`assets/source/reference/legacy-atlas-v0.8.webp`):
 *   - warm cream paper, brown desk
 *   - kiss-cut stickers: a thick off-white border hugging the silhouette
 *   - hand-cut wobble on that border (never on the artwork itself)
 *   - soft drop shadow so pieces read as physically lying on the desk
 *   - painted gouache fills with a visible darker ink line
 */

